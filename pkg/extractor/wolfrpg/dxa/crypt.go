var rcon = [11]byte{0x8D, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36}

func xtime(x byte) byte { return x<<1 ^ (x>>7)*0x1B }

func aesKeyExpansion(key [16]byte) [176]byte {
	var rk [176]byte
	copy(rk[:16], key[:])
	for i := 4; i < 44; i++ {
		t := [4]byte{rk[(i-1)*4], rk[(i-1)*4+1], rk[(i-1)*4+2], rk[(i-1)*4+3]}
		if i%4 == 0 {
			t = [4]byte{t[1], t[2], t[3], t[0]}
			t[0] = sbox[t[0]] ^ rcon[i/4]
			t[1] = sbox[t[1]] >> 4
			t[2] = ^sbox[t[2]]
			t[3] = rotr8(sbox[t[3]], 7)
		}
		for j := 0; j < 4; j++ {
			rk[i*4+j] = rk[(i-4)*4+j] ^ t[j]
		}
	}
	return rk
}

func shiftRows(s *[16]byte) {
	s[1], s[5], s[9], s[13] = s[5], s[9], s[13], s[1]
	s[2], s[10] = s[10], s[2]
	s[6], s[14] = s[14], s[6]
	s[3], s[7], s[11], s[15] = s[15], s[3], s[7], s[11]
}

func aesCipher(s *[16]byte, rk *[176]byte) {
	for i := range s {
		s[i] ^= rk[i]
	}
	for r := 1; r < 10; r++ {
		for i := range s {
			s[i] = sbox[s[i]]
		}
		shiftRows(s)
		for c := 0; c < 16; c += 4 {
			s0, s1, s2, s3 := s[c], s[c+1], s[c+2], s[c+3]
			t := s0 ^ s1 ^ s2 ^ s3
			s[c] ^= t ^ xtime(s1^s0)
			s[c+1] ^= t ^ xtime(s2^s1)
			s[c+2] ^= t ^ xtime(s2^s3)
			s[c+3] ^= t ^ xtime(s3^s0)
		}
		for i := range s {
			s[i] ^= rk[r*16+i]
		}
	}
	for i := range s {
		s[i] = sbox[s[i]]
	}
	shiftRows(s)
	for i := range s {
		s[i] ^= rk[160+i]
	}
}

// aesCTR é o fluxo de chave em modo CTR. O contador persiste entre chamadas a
// xor: o Wolf cifra o início do arquivo e depois as tabelas com o mesmo fluxo.
type aesCTR struct {
	rk [176]byte
	iv [16]byte
}

func newAESCTR(pwd []byte) *aesCTR {
	var key, iv [16]byte
	for i := 0; i < 15; i++ {
		key[i] ^= byte(int(pwd[(i*7)%15]) + i*i)
		iv[i] ^= byte(int(pwd[(i*11)%15]) - i*i)
		key[15] ^= byte(int(pwd[i]) + i*3)
		iv[15] ^= byte(int(pwd[i]) + i*5)
	}
	return &aesCTR{rk: aesKeyExpansion(key), iv: iv}
}

func (c *aesCTR) xor(data []byte) {
	var state [16]byte
	bi := 16
	for i := range data {
		if bi == 16 {
			state = c.iv
			aesCipher(&state, &c.rk)
			for j := 15; j >= 0; j-- {
				c.iv[j]++
				if c.iv[j] != 0 {
					break
				}
			}
			bi = 0
		}
		data[i] ^= state[bi]
		bi++
	}
}

// posKey é a tabela de 3x256 bytes do XOR por posição.
type posKey [768]byte

func calcSalt(key []byte) [128]byte {
	var salt [128]byte
	if len(key) == 0 {
		return salt
	}
	for i := range salt {
		salt[i] = byte(i/len(key) + int(key[i%len(key)]))
	}
	return salt
}

// newPosKey deriva a tabela a partir da senha de 15 bytes do cabeçalho. other
// seleciona a variante que também mistura a chave textual da versão do jogo.
func newPosKey(pwd, keyString []byte, other bool) *posKey {
	s0, s1, s2 := int(pwd[2]), int(pwd[5]), int(pwd[12])
	var s3 byte
	if !other {
		for i := 0; i < int(pwd[11])/3; i++ {
			s3 = byte(i) ^ rotr8(s3^pwd[i%15], 3)
		}
	} else {
		for i := 0; i < int(pwd[8])/4; i++ {
			s3 = byte(i) ^ rotr8(s3^pwd[i%15], 2)
		}
	}

	rng := &winRand{state: uint32(s0*s1 + s2 + int(s3))}
	var fac [3]int
	fac[int(s3)%3] = rng.next() % 256

	k := &posKey{}
	for i := 0; i < 256; i++ {
		rn := rng.next() & 0xFFFF
		k[i] = byte(fac[0] ^ (rng.next() & 0xFF))
		k[i+256] = byte(fac[1] ^ rn>>8)
		k[i+512] = byte(fac[2] ^ rn&0xFF)
	}

	if !other || len(keyString) == 0 {
		return k
	}
	salt := calcSalt(keyString)
	for i := 0; i < 3; i++ {
		t := int(s3)
		for j := 0; j < 256; j++ {
			skip := false
			curS := int(salt[j&0x7F])
			curS2 := int(salt[(j+i)%0x80])
			curK := int(k[i*256+j])
			sxk := curS ^ curK
			round := (curS2 | curS<<8) % 7
			newK := sxk

			switch round {
			case 1:
				if curS2%0xB == 0 {
					newK = curK
				}
			case 2:
				if curS%0x1D == 0 {
					newK = ^sxk & 0xFF
				}
			case 3:
				if (round+j)%0x25 == 0 {
					newK = curS2 ^ sxk
				}
			case 4:
				if (curS+curS2)%97 == 0 {
					newK = curS + sxk
				}
			case 5:
				if (j*round)%0x7B == 0 {
					newK = sxk ^ t
				}
			case 6:
				if curS == 0xFF && curS2 == 0 {
					newK = 0
					skip = true
				}
			}

			if (j+i)%(curS%5+1) == 0 {
				newK ^= t & 0xFF
			} else if skip {
				newK = ^sxk & 0xFF
			}
			k[i*256+j] = byte(newK)
			t += i
		}
	}
	return k
}

// xor aplica o fluxo de chave a data, que começa na posição start do fluxo.
func (k *posKey) xor(data []byte, start int) {
	for i := range data {
		p := start + i
		data[i] ^= k[p&0xFF] ^ k[256+(p>>8)&0xFF] ^ k[512+(p>>16)&0xFF]
	}
}

// scrambleHeader desfaz a ofuscação dos campos de endereço do cabeçalho de 64 bytes.
func scrambleHeader(head []byte, pwd []byte) {
	rng := &winRand{state: uint32(int(pwd[0]) + int(pwd[7])*int(pwd[12]))}
	for i := 0; i < 4; i++ {
		base := 4 + i*4
		for j := 3; j >= 0; j-- {
			off := (base + j) * 2
			v := binary.LittleEndian.Uint16(head[off:]) ^ uint16(rng.next())
			binary.LittleEndian.PutUint16(head[off:], v)
		}
	}
}

