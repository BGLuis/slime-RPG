// winRand é o gerador congruencial linear da MSVCRT.
type winRand struct{ state uint32 }

func (r *winRand) next() int {
	r.state = r.state*214013 + 2531011
	return int(r.state>>16) & 0x7FFF
}

func rotr8(v byte, r uint) byte { return v>>(r%8) | v<<(8-r%8) }

