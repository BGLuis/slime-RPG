func TestMVExtractor_PluginsJs(t *testing.T) {
	ext := NewMVExtractor()

	if !ext.CanHandle("plugins.js") {
		t.Errorf("expected CanHandle('plugins.js') to be true")
	}
	if !ext.CanHandle("www/js/plugins.js") {
		t.Errorf("expected CanHandle('www/js/plugins.js') to be true")
	}

	sampleJS := `// Generated by RPG Maker.
// Do not modify this file directly.
var $plugins =
[
  {
    "name": "CustomMenu",
    "status": true,
    "description": "Menu customizado",
    "parameters": {
      "MenuTitle": "Configurações do Jogo",
      "BgmName": "Theme1.ogg",
      "SwitchId": "12",
      "SubConfig": "{\"OptionA\":\"Velocidade da Mensagem\",\"AssetIcon\":\"icon.png\"}"
    }
  },
  {
    "name": "InactivePlugin",
    "status": false,
    "description": "Inativo",
    "parameters": {
      "IgnoredText": "Não deve extrair"
    }
  }
];
`

	segments, err := ext.Extract("plugins.js", []byte(sampleJS))
	if err != nil {
		t.Fatalf("Extract failed: %v", err)
	}

	if len(segments) != 2 {
		t.Fatalf("expected 2 extracted segments (MenuTitle and OptionA), got %d", len(segments))
	}

	// Verifica se BgmName e SwitchId foram ignorados
	for _, s := range segments {
		if strings.Contains(s.Source(), "Theme1.ogg") || strings.Contains(s.Source(), "icon.png") {
			t.Errorf("technical asset was erroneously extracted: %s", s.Source())
		}
	}

	// Cria tradução
	var resolved []*model.Segment
	for _, s := range segments {
		if strings.Contains(s.Source(), "Configurações") {
			s = s.WithTarget("Game Settings")
		} else if strings.Contains(s.Source(), "Velocidade") {
			s = s.WithTarget("Message Speed")
		}
		resolved = append(resolved, s)
	}

	// Inject
	injected, err := ext.Inject("plugins.js", []byte(sampleJS), resolved)
	if err != nil {
		t.Fatalf("Inject failed: %v", err)
	}

	injectedStr := string(injected)
	if !strings.Contains(injectedStr, "var $plugins =") {
		t.Errorf("expected header 'var $plugins =' preserved")
	}
	if !strings.Contains(injectedStr, "Game Settings") {
		t.Errorf("expected translated 'Game Settings' in output")
	}
	if !strings.Contains(injectedStr, "Message Speed") {
		t.Errorf("expected translated 'Message Speed' in output")
	}
	if !strings.Contains(injectedStr, "Theme1.ogg") {
		t.Errorf("expected untouched asset 'Theme1.ogg' in output")
	}
}

// Sem traduções o arquivo precisa sair idêntico; com traduções, só as strings
// traduzidas mudam (inclusive dentro de structs do MZ serializados em string).
func TestPluginsJsInjectPreservesBytes(t *testing.T) {
	ext := NewMVExtractor()
	src := "// Generated by RPG Maker.\nvar $plugins =\n[\n{\"name\":\"Menu\",\"status\":true,\"description\":\"<b>&</b>\",\"parameters\":{" +
		"\"Title\":\"冒険の書\"," +
		"\"Struct\":\"{\\\"Label\\\":\\\"はい\\\",\\\"Icon\\\":\\\"12\\\",\\\"List\\\":\\\"[\\\\\\\"いいえ\\\\\\\"]\\\"}\"," +
		"\"Align\":\"center\"}}\n];\n"

	segs, err := ext.Extract("plugins.js", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, s := range segs {
		got[s.Source()] = s.ID()
	}
	for _, want := range []string{"冒険の書", "はい", "いいえ"} {
		if _, ok := got[want]; !ok {
			t.Errorf("faltou extrair %q: %v", want, got)
		}
	}
	if len(segs) != 3 {
		t.Errorf("esperava 3 segmentos (Align é configuração), obteve %d", len(segs))
	}

	same, err := ext.Inject("plugins.js", []byte(src), segs)
	if err != nil || string(same) != src {
		t.Fatalf("sem tradução o arquivo deveria sair idêntico (err=%v):\n%s", err, same)
	}

	dict := map[string]string{"冒険の書": "Livro de Aventuras", "はい": "Sim", "いいえ": "Não"}
	var resolved []*model.Segment
	for _, s := range segs {
		resolved = append(resolved, s.WithTarget(dict[s.Source()]))
	}
	out, err := ext.Inject("plugins.js", []byte(src), resolved)
	if err != nil {
		t.Fatal(err)
	}
	want := strings.NewReplacer("冒険の書", "Livro de Aventuras", "はい", "Sim", "いいえ", "Não").Replace(src)
	if string(out) != want {
		t.Errorf("injeção alterou mais do que as strings traduzidas:\n got: %s\nwant: %s", out, want)
	}

	again, err := ext.Extract("plugins.js", out)
	if err != nil || len(again) != 3 {
		t.Fatalf("o resultado precisa continuar sendo um plugins.js válido: %v (%d segmentos)", err, len(again))
	}
}

// Porte de tests/test_plugins_js_extractor.py: structs do MZ aninhados em vários
// níveis, plugins inativos e parâmetros técnicos.
func TestPluginsJsPythonFixture(t *testing.T) {
	src, err := os.ReadFile("testdata/plugins_python.js")
	if err != nil {
		t.Fatal(err)
	}
	ext := NewMVExtractor()
	segs, err := ext.Extract("plugins.js", src)
	if err != nil {
		t.Fatal(err)
	}

	sources := map[string]bool{}
	for _, s := range segs {
		sources[s.Source()] = true
	}
	for _, want := range []string{"主人公名変更", "主人公の見た目", "ノーマル", "種付けマスター", "エロシーンピストンオート", "断面図表示", "喘ぎ声 音量", "難易度", "イージー", "ハード"} {
		if !sources[want] {
			t.Errorf("faltou extrair %q", want)
		}
	}
	for _, unwanted := range []string{"無視されるべきテキスト", "SceneManager.push(Scene_Name);", "auto", "1080", "0", "20"} {
		if sources[unwanted] {
			t.Errorf("%q não deveria ser extraído", unwanted)
		}
	}

	var resolved []*model.Segment
	for _, s := range segs {
		resolved = append(resolved, s.WithTarget("PT_"+s.Source()))
	}
	out, err := ext.Inject("plugins.js", src, resolved)
	if err != nil {
		t.Fatal(err)
	}

	start, end, err := pluginsArray(out)
	if err != nil {
		t.Fatal(err)
	}
	var plugins []map[string]any
	if err := json.Unmarshal(out[start:end], &plugins); err != nil {
		t.Fatalf("plugins.js inválido após a injeção: %v", err)
	}
	var items []string
	_ = json.Unmarshal([]byte(plugins[1]["parameters"].(map[string]any)["文字項目"].(string)), &items)
	var item0, item1 map[string]string
	_ = json.Unmarshal([]byte(items[0]), &item0)
	_ = json.Unmarshal([]byte(items[1]), &item1)
	if item0["Name"] != "PT_主人公名変更" || item0["Script"] != "SceneManager.push(Scene_Name);" {
		t.Errorf("item0 = %v", item0)
	}
	var strItems []string
	_ = json.Unmarshal([]byte(item1["StringItems"]), &strItems)
	if len(strItems) != 2 || strItems[0] != "PT_ノーマル" || strItems[1] != "PT_種付けマスター" {
		t.Errorf("StringItems = %v", strItems)
	}
	diff := plugins[2]["parameters"].(map[string]any)
	if diff["Option Name"] != "PT_難易度" || diff["1 : Name"] != "PT_イージー" {
		t.Errorf("Vitsuno_Difficulty = %v", diff)
	}
	if plugins[3]["parameters"].(map[string]any)["Option"] != "無視されるべきテキスト" {
		t.Error("plugin inativo não pode ser alterado")
	}
}
